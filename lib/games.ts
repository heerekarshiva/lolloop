export const bySlug = (slug: string): GameInfo | undefined => {
  return GAMES.find((g) => g.slug === slug);
};

export const byCategory = (cat: GameCategory): GameInfo[] => {
  return GAMES.filter((g) => g.category === cat);
};

export const dailyGame = (d = new Date()): GameInfo => {
  const index = Math.floor(d.getTime() / 86_400_000) % GAMES.length;
  return GAMES[index];
};

export const fmtScore = (g: GameInfo, v: number): string => {
  if (g.unit === 'sec') return `${v}s`;
  if (g.unit === 'ms') return `${(v / 1000).toFixed(2)}s`;
  if (g.unit === 'rank') return `#${v} Place`;
  return `${v} ${g.unit}`;
};

export const fmt = fmtScore;
